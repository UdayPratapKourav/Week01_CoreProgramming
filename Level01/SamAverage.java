

class SamAverage {
    public static void main(String[] args) {
        // Declare Sam's marks in Math, Physics and Chemistry
        int math = 94;
        int physics = 95;
        int chemistry = 96;
		

        // Calculate Sam's average mark
        int averageMark = (math+physics+chemistry)/3;

        // Print Sam's average mark
        System.out.println("Sam's average mark in PCM is " + averageMark);
    }
}
